--1
SELECT FIRST_NAME,
    LAST_NAME,
    JOB_ID
FROM HR.EMPLOYEES
WHERE LOWER(FIRST_NAME) = 'david';

--2
SELECT FIRST_NAME, LAST_NAME, HIRE_DATE FROM HR.EMPLOYEES
WHERE HIRE_DATE < TO_DATE('31-12-2007', 'DD-MM-YYYY');

--3
SELECT CITY, POSTAL_CODE FROM HR.LOCATIONS
WHERE POSTAL_CODE LIKE '9%';

--4
SELECT JOB_TITLE, MAX_SALARY FROM HR.JOBS
WHERE MAX_SALARY > 10000;
ORDER BY MAX_SALARY ASCI

--5
SELECT DEPARTMENT_NAME, MANAGER_ID FROM HR.DEPARTMENTS
WHERE MANAGER_ID IS NOT NULL;

--6
SELECT FIRST_NAME, DEPARTMENT_ID || ' DEPT' AS "SOBE_KODU" FROM HR.EMPLOYEES;

--7
SELECT COUNT(JOB_ID) FROM HR.EMPLOYEES
WHERE JOB_ID = 'ST_CLERK';

--8
SELECT FIRST_NAME, HIRE_DATE FROM HR.EMPLOYEES
WHERE EXTRACT(YEAR FROM HIRE_DATE) = 2008 AND EXTRACT(MONTH FROM HIRE_DATE) = 1;

--9
SELECT FIRST_NAME, LAST_NAME, COMMISSION_PCT FROM HR.EMPLOYEES
WHERE COMMISSION_PCT >= 0.15;

--10
SELECT JOB_TITLE FROM HR.JOBS
ORDER BY MAX_SALARY DESC
FETCH FIRST 3 ROWS ONLY;

--11
SELECT FIRST_NAME, SALARY, SALARY * 0.1 + SALARY * NVL(COMMISSION_PCT, 0) AS "BONUS" FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;

--12
SELECT FIRST_NAME, LAST_NAME, HIRE_DATE FROM HR.EMPLOYEES
WHERE EXTRACT(YEAR FROM HIRE_DATE) > 2004 AND EXTRACT(MONTH FROM HIRE_DATE) = 6;

--13
SELECT MIN(SALARY) AS "MIN_MAAS", MAX(SALARY) AS "MAX_MAAS", ROUND(AVG(SALARY)) AS "ORTA_MAAS" FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 50;

--14
SELECT FIRST_NAME, ROUND(SALARY * 12, 2) AS "ILLIK_BRUTO", ROUND(SALARY * 12 * 15/100, 2) AS "ILLIK_VERGI", 
    ROUND(SALARY * 12 * 85 / 100, 2)
FROM HR.EMPLOYEES;
