--1
SELECT FIRST_NAME, 
    LAST_NAME, 
    SALARY,
    NVL(COMMISSION_PCT, 0) AS "DUZELDILMIS_KOMISSIYA"
FROM HR.EMPLOYEES;

--2
SELECT FIRST_NAME, 
    LAST_NAME,
    SALARY
    FROM HR.EMPLOYEES
WHERE UPPER(LAST_NAME) = 'KING';

--3
SELECT FIRST_NAME,
    LAST_NAME,
    HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE > TO_DATE('01-01-2006', 'DD-MM-YYYY');

--4
SELECT FIRST_NAME,
    LAST_NAME,
    ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)) AS STAZ_AY
FROM HR.EMPLOYEES;
--5
SELECT FIRST_NAME,
    LAST_NAME,
    PHONE_NUMBER
FROM HR.EMPLOYEES
WHERE PHONE_NUMBER LIKE '1.515%';

--6
SELECT JOB_TITLE,
    MIN_SALARY
FROM HR.JOBS
WHERE MIN_SALARY < 3000
ORDER BY MIN_SALARY DESC;

--7
SELECT CITY,
    STREET_ADDRESS
FROM HR.LOCATIONS
WHERE POSTAL_CODE IS NULL;

--8
SELECT FIRST_NAME,
    LAST_NAME,
    SALARY || ' USD' AS MAAS_VALYUTA
FROM HR.EMPLOYEES;

--9
SELECT COUNT(*) FROM HR.JOBS
WHERE MAX_SALARY > 20000;

--10
SELECT FIRST_NAME,
    HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE >= TO_DATE('01-01-2005', 'DD-MM-YYYY') AND HIRE_DATE < TO_DATE('01-01-2006', 'DD-MM-YYYY');

--11
SELECT FIRST_NAME,
    SALARY,
    ROUND(SALARY*80/100, 2) AS "NET_MAAS"
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;
--12
SELECT FIRST_NAME,
    HIRE_DATE,
    JOB_ID
FROM HR.EMPLOYEES
WHERE JOB_ID <> 'IT_PROG' AND 
    HIRE_DATE >= TO_DATE('01-01-2003', 'DD-MM-YYYY') AND HIRE_DATE < TO_DATE('01-01-2006', 'DD-MM-YYYY');

--13
SELECT COUNT(*) AS "KOMISSIYA_ALMAYAN",
    ROUND(AVG(SALARY)) AS "ORTA_MAAS"
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NULL;

--14
SELECT FIRST_NAME,
    SALARY
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL AND DEPARTMENT_ID IS NOT NULL
ORDER BY SALARY DESC
FETCH FIRST 3 ROWS ONLY;

--15
SELECT FIRST_NAME,
    LAST_NAME,
    EXTRACT(DAY FROM HIRE_DATE)
FROM HR.EMPLOYEES
WHERE EXTRACT(DAY FROM HIRE_DATE) > 15 AND SALARY BETWEEN 5000 AND 12000;
