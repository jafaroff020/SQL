-- TASK 1
SELECT FIRST_NAME, LAST_NAME, SALARY, SALARY * 110/100 AS "YENI_MAAS"
FROM HR.EMPLOYEES;

-- TASK 2
SELECT DISTINCT COUNTRY_ID FROM HR.LOCATIONS;

-- TASK 3
SELECT FIRST_NAME, DEPARTMENT_ID, SALARY FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 50 AND SALARY < 3000 OR 
        (DEPARTMENT_ID = 80 AND SALARY > 10000)

-- TASK 4
SELECT JOB_TITLE, MIN_SALARY FROM HR.JOBS
WHERE MIN_SALARY BETWEEN 4000 AND 6000;

-- TASK 5
SELECT CITY, COUNTRY_ID FROM HR.LOCATIONS
WHERE COUNTRY_ID IN ('US', 'UK', 'CA');

-- TASK 6
SELECT FIRST_NAME, LAST_NAME FROM HR.EMPLOYEES
WHERE FIRST_NAME LIKE 'S____' AND LAST_NAME LIKE '%a%';

-- TASK 7
SELECT DEPARTMENT_NAME FROM HR.DEPARTMENTS
WHERE MANAGER_ID IS NULL;

-- TASK 8
SELECT JOB_TITLE, MAX_SALARY - MIN_SALARY AS "MAAS_FERQI" FROM HR.JOBS
ORDER BY MAX_SALARY - MIN_SALARY DESC
FETCH FIRST 3 ROWS ONLY;

-- TASK 9
SELECT COUNT(EMPLOYEE_ID) AS "ISCILERIN_SAYI",
       COUNT(COMMISSION_PCT) AS "KOMISSIYA_ALANLAR",
       ROUND(AVG(SALARY), 2) AS "ORTA_MAAS",
       MAX(SALARY) - MIN(SALARY) AS "MAX_MIN_FERQI"
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;

-- TASK 10
