-- TASK 1
SELECT MANAGER_ID, COUNT(EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;

-- TASK 2
SELECT COUNTRY_ID, COUNT(LOCATION_ID) AS OFIS_SAYI
FROM HR.LOCATIONS
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC;

-- TASK 3
SELECT E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE
FROM HR.EMPLOYEES E
LEFT JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID;

-- TASK 4
SELECT DEPARTMENT_ID, ROUND(AVG(SALARY), 2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING ORTA_MAAS > 8000;

-- TASK 5
SELECT DEPARTMENT_ID, COUNT(EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY >= 3000
GROUP BY DEPARTMENT_ID
HAVING ISCI_SAYI > 3;

-- TASK 6
SELECT J.JOB_TITLE, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID
GROUP BY JOB_TITLE
ORDER BY ISCI_SAYI DESC;

-- TASK 7
SELECT L.CITY, L.COUNTRY_ID
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D
ON L.LOCATION_ID = D.LOCATION_ID
WHERE D.DEPARTMENT_ID IS NULL;

-- TASK 8
SELECT J.JOB_TITLE, AVG(E.SALARY) AS ORTA_MAAS -- LAST_NAME ARTIQDIR
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID -- J.JOB_ID OLMALIDI
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000 -- WHERE-I HAVING ILE EVEZ EDIRIK

-- TASK 9
SELECT L.CITY, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI, ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
JOIN HR.LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
HAVING ISCI_SAYI > 5
ORDER BY ISCI_SAYI DESC;

-- TASK 10
SELECT D.DEPARTMENT_NAME, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC, DEPARTMENT_NAME;

----------------------------------------------------------------DERS3-------------------------------------------------------------------

-- TASK 1
SELECT FIRST_NAME, LAST_NAME, SALARY,
    CASE
        WHEN SALARY < 6000 THEN 'ASAGI'
        WHEN SALARY BETWEEN 6000 AND 12000 THEN 'ORTA'
        ELSE 'YUKSEK'
    END AS MAAS_SEVIYYESI
FROM HR.EMPLOYEES;

-- TASK 2
SELECT FIRST_NAME, JOB_ID,
    CASE JOB_ID
        WHEN 'IT_PROG' THEN 'PROQRAMCI'
        WHEN 'SA_REP' THEN 'SATIS NUMAYENDESI'
        WHEN 'ST_CLERK' THEN 'ANBAR ISCISI'
        ELSE 'DIGER'
    END AS VEZIFE
FROM HR.EMPLOYEES;

-- TASK 3
SELECT FIRST_NAME, COMMISSION_PCT, 
       NVL2(COMMISSION_PCT, 'KOMISSIYA VAR', 'KOMISSIYA YOXDUR') AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

-- TASK 3(CASE ILE)
SELECT FIRST_NAME, COMMISSION_PCT,
    CASE
        WHEN COMMISSION_PCT IS NULL THEN 'KOMISSIYA YOXDUR'
        ELSE 'KOMISSIYA VAR'
    END AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

-- TASK 4
SELECT CITY, COUNTRY_ID,
    CASE
        WHEN COUNTRY_ID IN ('US', 'CA', 'MX', 'BR') THEN 'AMERIKA'
        WHEN COUNTRY_ID IN ('UK', 'DE', 'IT', 'NL', 'CH') THEN 'AVROPA'
        WHEN COUNTRY_ID IN ('JP', 'CN', 'IN', 'SG') THEN 'ASIYA'
        ELSE 'DIGER'
    END AS QITE
FROM HR.LOCATIONS;

-- TASK 5
SELECT FIRST_NAME, DEPARTMENT_ID, SALARY,
    CASE DEPARTMENT_ID
        WHEN 80 THEN SALARY * 0.1
        WHEN 60 THEN SALARY * 0.15
        ELSE SALARY * 0.05
    END AS BONUS
FROM HR.EMPLOYEES
ORDER BY BONUS DESC;

-- TASK 6
SELECT FIRST_NAME, SALARY,
    CASE
        WHEN SALARY > 15000 THEN 'YUKSEK' -- CASE SIRA ILE YOXLAYIR ONA GORE BIRINCI YUKSEK OLMALIDI
        WHEN SALARY > 5000 THEN 'ORTA'
        ELSE 'ASAGI' -- SUTUNDA EYNI TIP VERILEN OLMALIDI 0 OLMAZ
    END AS SEVIYYE -- '' ILE ALIAS YAZILMAZ
FROM HR.EMPLOYEES;

-- TASK 7
SELECT FIRST_NAME, JOB_ID, MANAGER_ID,
    CASE
        WHEN MANAGER_ID IS NULL THEN 'DIREKTOR'
        WHEN MANAGER_ID = 100 THEN 'DIREKTORUN KOMANDASI'
        WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'MENECER'
        ELSE 'ISCI'
    END AS ROL
FROM HR.EMPLOYEES;

-- TASK 8
SELECT FIRST_NAME, SALARY, COMMISSION_PCT,
       NVL(SALARY * COMMISSION_PCT * 12, 0) AS ILLIK_KOMISSIYA,
       NVL2(COMMISSION_PCT, (SALARY * 12) + SALARY * COMMISSION_PCT * 12, SALARY * 12) AS ILLIK_GELIR
FROM HR.EMPLOYEES
ORDER BY ILLIK_GELIR DESC;

-- TASK 8(SADECE NVL ILE DE OLUR)
SELECT FIRST_NAME, SALARY, COMMISSION_PCT,
       NVL(SALARY * COMMISSION_PCT * 12, 0) AS ILLIK_KOMISSIYA,
       (SALARY * 12) + NVL(SALARY * COMMISSION_PCT * 12, 0) AS ILLIK_GELIR
FROM HR.EMPLOYEES
ORDER BY ILLIK_GELIR DESC;

-- TASK 9
SELECT E.FIRST_NAME, J.JOB_TITLE, E.SALARY, J.MIN_SALARY, J.MAX_SALARY,
    CASE
        WHEN E.SALARY = J.MIN_SALARY THEN 'MINIMUMDA'
        WHEN E.SALARY = J.MAX_SALARY THEN 'MAKSIMUMDA'
        WHEN E.SALARY < (J.MIN_SALARY + J.MAX_SALARY) / 2 THEN 'ASAGI YARIDA'
        ELSE 'YUXARI YARIDA'
    END AS MOVQE
FROM HR.EMPLOYEES E
LEFT JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID;

-- TASK 10
SELECT E.FIRST_NAME, E.LAST_NAME,
       NVL(D.DEPARTMENT_NAME, 'SOBESIZ') AS SOBE,
    CASE
        WHEN D.DEPARTMENT_ID IS NULL THEN 'MELUM DEYIL'
        WHEN L.CITY = 'Seattle' THEN 'BAS OFIS'
        ELSE 'FILIAL'
    END AS OFIS
FROM HR.EMPLOYEES E
LEFT JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID;

-- TASK 10(NVL2 ILE DE BELE OLAR)
SELECT E.FIRST_NAME, E.LAST_NAME,
       NVL2(D.DEPARTMENT_ID, D.DEPARTMENT_NAME, 'SOBESIZ') AS SOBE,
    CASE
        WHEN E.DEPARTMENT_ID IS NULL THEN 'MELUM DEYIL'
        WHEN L.CITY = 'Seattle' THEN 'BAS OFIS'
        ELSE 'FILIAL'
    END AS OFIS
FROM HR.EMPLOYEES E
LEFT JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID;
